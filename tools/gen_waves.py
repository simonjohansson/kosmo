"""Wavetables for Kosmo's WAVE engine: 8 tables x 8 frames x 256 int16 samples, each table morphing from
simple (frame 0) to bright (frame 7). Additive, peak-normalised per frame. Writes a C header.
  tools/gen_waves.py build/gen/kosmo_waves.h"""
import math
import sys

N, FRAMES = 256, 8
G = lambda h, c, w: math.exp(-((h - c) / w) ** 2)


def harm(fn):                           # a table from fn(h, t) -> partial amplitude, t = frame / 7
    return lambda t: lambda x: sum(fn(h, t) * math.sin(2 * math.pi * h * x) for h in range(1, 41))


TABLES = [
    harm(lambda h, t: (h % 2) / h ** (2 - 1.6 * t)),                                   # ROBOT: sine -> square -> hard
    harm(lambda h, t: G(h, 2 + 2 * t, 1.2) + 0.6 * G(h, 5 + 6 * t, 1.5)),              # CHOIR: moving formants
    harm(lambda h, t: (h in (1, 2, 4, 5, 7, 9, 12)) * (1 if h < 3 else t) / h ** .5),  # BELLS: sparse partials
    harm(lambda h, t: (h <= 1 + 39 * t) / h),                                          # BUZZ: saw opening up
    harm(lambda h, t: (h in (1, 2, 3, 4, 6, 8)) * (1 if h == 1 else t) / h ** .5),     # ORGAN: drawbars in
    harm(lambda h, t: (h == 1) + 0.7 * G(h, 2 + 10 * t, 1.0)),                         # GLASS: one bright peak sweeps
    harm(lambda h, t: math.sin(math.pi * h * (0.5 - 0.45 * t)) / h),                   # PULSE: width 50% -> 5%
    lambda t: lambda x: math.sin(2 * math.pi * x + 4 * t * math.sin(2 * math.pi * x)),  # ZAP: FM index 0 -> 4
]


def main(path):
    out = ["/* generated by tools/gen_waves.py */", "#pragma once", "#include <stdint.h>",
           f"static const int16_t WAVES[{len(TABLES)}][{FRAMES}][{N}] = {{"]
    for tab in TABLES:
        out.append(" {")
        for f in range(FRAMES):
            s = [tab(f / (FRAMES - 1))(i / N) for i in range(N)]
            pk = max(abs(v) for v in s)
            out.append("  {" + ",".join(str(round(v / pk * 32000)) for v in s) + "},")
        out.append(" },")
    out.append("};")
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")


main(sys.argv[1])
